#!/usr/bin/env python3
"""
Gives every downloaded paper a stable id and writes the readable citation table.
Run after scripts/pyq-fetch.py. Updates docs/content/pyq-sources.json and writes
docs/content/PYQ_SOURCES.md.

Paper id: <year>-<exam>-<level>-<code>, for example 2019-main-std-30-1-1. Use it to
link a tagged question or a question pattern back to its source file.
"""
import collections
import datetime
import json
import os
import re
import subprocess
import tempfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'docs/content')
path = os.path.join(ROOT, 'pyq-sources.json')
doc = json.load(open(path))
Counter = collections.Counter

# Checked by eye: these copies were retyped by the publisher, so they aren't the printed paper.
RETYPED = {'CBSE-Class-10-Maths-Question-Paper-2011.pdf', 'CBSE-Class-10-Maths-Question-Paper-2012.pdf', 'CBSE-Class-10-Maths-Question-Paper-2014.pdf'}
REPRODUCED = {'cbse-class-10-maths-question-paper-2011-delhi-scheme.pdf'}


def first_page_text(p):
    t = subprocess.run(['pdftotext', '-l', '1', p, '-'], capture_output=True, text=True, timeout=30).stdout
    if len(t.strip()) > 200:
        return t
    with tempfile.TemporaryDirectory() as d:
        subprocess.run(['pdftoppm', '-r', '150', '-f', '1', '-l', '1', '-gray', '-png', '-singlefile', p, f'{d}/p'], timeout=60)
        return subprocess.run(['tesseract', f'{d}/p.png', '-', '-l', 'eng'], capture_output=True, text=True, timeout=90).stdout


CODE = re.compile(r'(?<![0-9])(430|30|40|46)\s*[-/_ ]\s*([0-9CSBcsb]{1,2})\s*[-/_ ]\s*([0-9])(?![0-9])')


def code_of(name, text):
    m = CODE.search(name)
    if m:
        return '/'.join(m.groups()).upper()
    m = re.search(r'(?<![0-9])(430|30|40|46)\s*\(?([Bb])\)?', name)
    if m:
        return f'{m.group(1)}(B)'
    m = re.search(r'(?<![0-9])(030|30|40|46)[ -]+(?:SET[ -]*)?([1-3])\b', name, re.I)
    if m:
        return f"{m.group(1).lstrip('0')}/{m.group(2)}"
    m = re.search(r'(?<![0-9])0?30 Set ([1-3])', name)
    if m:
        return f'30/{m.group(1)}'
    m = CODE.search(text) or None
    if m:
        return '/'.join(m.groups()).upper()
    m = re.search(r'(?<![0-9/])(430|30)/([0-9])(?![0-9/])', text)
    return f'{m.group(1)}/{m.group(2)}' if m else None


seen = {}
for f in doc['files']:
    p = os.path.join(ROOT, f['file'])
    name = os.path.basename(p)
    text = first_page_text(p) if f.get('readable') else ''
    f['setCode'] = code_of(name, text if f['kind'] == 'question-paper' else '')
    s = re.search(r'Series\s*[:\-]?\s*([A-Z]{2,5}\s*/?\s*[0-9]*)', text)
    f['series'] = re.sub(r'\s+', '', s.group(1)) if s else None
    if name in RETYPED:
        f['fidelity'] = 'retyped'
    elif name in REPRODUCED:
        f['fidelity'] = 'reproduced'
    elif f['sourceType'] == 'official':
        f['fidelity'] = 'official-original'
    else:
        f['fidelity'] = 'copy-of-printed-paper' if f['kind'] == 'question-paper' else 'publisher-solution' if f['kind'] == 'solution' else 'copy-of-marking-scheme'
    lvl = {'standard': 'std', 'basic': 'bas', 'single-level': 'std'}[f['level']]
    code = (f['setCode'] or 'unknown').replace('/', '-').replace('(', '').replace(')', '')
    kind = '' if f['kind'] == 'question-paper' else '-' + f['kind']
    f['paperId'] = f"{f['year']}-{f['exam']}-{lvl}-{code}{kind}"
    first = seen.get(f['sha256'])
    if first:
        f['duplicateOf'] = first
    else:
        seen[f['sha256']] = f['paperId']

# Several copies of a paper share an id; the most trusted is the one to use.
RANK = ['official-original', 'copy-of-printed-paper', 'reproduced', 'retyped']
best = {}
for f in doc['files']:
    r = RANK.index(f['fidelity']) if f['fidelity'] in RANK else 9
    if f['paperId'] not in best or r < best[f['paperId']][0]:
        best[f['paperId']] = (r, f)
for f in doc['files']:
    f['primary'] = best[f['paperId']][1] is f and not f.get('duplicateOf')

json.dump(doc, open(path, 'w'), ensure_ascii=False, indent=1)

F = doc['files']
Q = [f for f in F if f['kind'] == 'question-paper' and f['variant'] == 'english-hindi' and not f.get('duplicateOf')]
L = ['# Sources: CBSE Class 10 Mathematics board papers', '',
     f'Generated by `scripts/pyq-index.py` on {datetime.date.today().isoformat()}. Full record for every file, with its checksum, in [pyq-sources.json](pyq-sources.json). The PDFs are in `docs/content/pyq/`, which is not in git.', '',
     '**Trust, highest first:** `official-original` is from cbse.gov.in. `copy-of-printed-paper` is a third-party scan or PDF showing the real series and code. `reproduced` keeps the paper\'s codes but was re-set by the publisher. `retyped` has no codes and may contain typing errors.', '',
     '## Coverage by year (English-Hindi question papers, no duplicates)', '',
     '| Year | Exam | Standard or single level | Basic | Best source | Publisher |', '|---|---|---|---|---|---|']
groups = collections.defaultdict(list)
for f in Q:
    groups[(f['year'], f['exam'])].append(f)
for (y, e), g in sorted(groups.items()):
    best = min((f['fidelity'] for f in g), key=lambda x: RANK.index(x) if x in RANK else 9)
    pubs = sorted({f['publisher'] for f in g if f['fidelity'] == best})
    L.append(f"| {y} | {e} | {sum(f['level'] != 'basic' for f in g)} | {sum(f['level'] == 'basic' for f in g)} | {best} | {', '.join(pubs)} |")
L += ['', '## Source pages cited', '', '| Publisher | Type | Years | Files | Page |', '|---|---|---|---|---|']
pages = collections.defaultdict(list)
for f in F:
    pages[(f['publisher'], f['sourceType'], f['citedPage'])].append(f)
for (pub, st, page), g in sorted(pages.items(), key=lambda x: (x[0][1] != 'official', sorted(f['year'] for f in x[1])[0])):
    ys = sorted({f['year'] for f in g})
    L.append(f"| {pub} | {st} | {ys[0]}{'-' + str(ys[-1]) if len(ys) > 1 else ''} | {len(g)} | {page} |")
L += ['', '## Every question paper', '', '| Paper id | Code | Series | Pages | Trust | File source |', '|---|---|---|---|---|---|']
for f in sorted(Q, key=lambda f: (f['year'], f['exam'], f['level'], f['setCode'] or '', f['fidelity'])):
    L.append(f"| {f['paperId']} | {f['setCode'] or '?'} | {f['series'] or ''} | {f['pages']} | {f['fidelity']} | [{f['publisher'] if f['sourceType'] != 'official' else 'CBSE'}]({f['sourceUrl'].replace(' ', '%20')}) |")
open(os.path.join(ROOT, 'PYQ_SOURCES.md'), 'w').write('\n'.join(L) + '\n')
print(len(F), 'files;', len(Q), 'unique English-Hindi question papers;', sum(1 for f in Q if not f['setCode']), 'without a code;', sum(1 for f in F if f.get('duplicateOf')), 'duplicates')
print(Counter(f['fidelity'] for f in Q))
ids = Counter(f['paperId'] for f in Q)
print('repeated ids', [k for k, v in ids.items() if v > 1][:30])
