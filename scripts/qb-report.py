#!/usr/bin/env python3
"""
Question-bank coverage report for CBSE Class 10 Maths (Standard).

Reads the question patterns (docs/content/question-patterns/*.json) and the live
bank (prisma/dev.db), and writes two files:
  docs/content/question-bank-status.md   topic x difficulty tables: target, have, gap
  docs/content/question-patterns.md      every question pattern with its board history

A question counts towards a pattern when its id is in that pattern's `existingIds`
and it is active. Re-run after importing questions:  python3 scripts/qb-report.py
"""
import collections
import glob
import json
import os
import sqlite3

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
DIR = os.path.join(ROOT, 'docs/content/question-patterns')
ORDER = ['real-numbers', 'polynomials', 'pair-of-linear-equations', 'quadratic-equations', 'arithmetic-progressions',
         'triangles', 'coordinate-geometry', 'trigonometry', 'circles', 'areas-related-to-circles',
         'surface-areas-and-volumes', 'statistics', 'probability']
SLOTS = ['A-MCQ', 'A-AR', 'B', 'C', 'D', 'E']
SLOT_NAME = {'A-MCQ': 'MCQ (1)', 'A-AR': 'Assertion-reason (1)', 'B': 'Short (2)', 'C': 'Short (3)', 'D': 'Long (5)', 'E': 'Case study (4)'}
DIFF = ('easy', 'medium', 'hard')
Counter = collections.Counter


def esc(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')


def triple(c):
    return f"{c['easy']} / {c['medium']} / {c['hard']}"


def table(head, rows):
    out = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    out += ['| ' + ' | '.join(str(x) for x in r) + ' |' for r in rows]
    return out


def last_asked(p):
    return max((int(s.split()[0]) for s in p.get('seenIn', [])), default=None)


db = sqlite3.connect(os.path.join(ROOT, 'prisma/dev.db'))
live = {i: c for i, c in db.execute('select id, complexity from questions where isActive = 1')}

chapters = []
for slug in ORDER:
    d = json.load(open(os.path.join(DIR, f'{slug}.json')))
    for t in d['topics']:
        for p in t['patterns']:
            p['have'] = Counter(live[i] for i in p['existingIds'] if i in live)
            p['total'] = sum(p['targets'].get(k, 0) for k in DIFF)
            p['gap'] = Counter({k: max(0, p['targets'].get(k, 0) - p['have'][k]) for k in DIFF})
    chapters.append(d)

# ── status ──────────────────────────────────────────────────────────────────
S = ['# Question bank status: CBSE Class 10 Maths (Standard)', '',
     'Generated by `scripts/qb-report.py`; do not edit by hand. Difficulty columns read easy / medium / hard.',
     '`Gap` is what each pattern still needs. Questions beyond a pattern\'s target, or in a pattern with no target, do not reduce the gap.', '']

total_t, total_h, total_g = Counter(), Counter(), Counter()
slot_t, slot_g = collections.defaultdict(Counter), collections.defaultdict(Counter)
chap_rows = []
for d in chapters:
    ct, ch, cg = Counter(), Counter(), Counter()
    fig = held = n = 0
    for t in d['topics']:
        for p in t['patterns']:
            n += 1
            for k in DIFF:
                ct[k] += p['targets'].get(k, 0)
                cg[k] += p['gap'][k]
                ch[k] += p['have'][k]
                slot_t[p['slot']][k] += p['targets'].get(k, 0)
                slot_g[p['slot']][k] += p['gap'][k]
            if p['figure']:
                fig += p['total']
            if not p['total']:
                held += sum(p['have'].values())
    chap_rows.append([d['chapter'], n, sum(ct.values()), triple(ct), sum(ch.values()), sum(cg.values()), triple(cg), fig, held])
    total_t.update(ct); total_h.update(ch); total_g.update(cg)
chap_rows.append(['**Total**', sum(r[1] for r in chap_rows), sum(total_t.values()), triple(total_t), sum(total_h.values()),
                  sum(total_g.values()), triple(total_g), sum(r[7] for r in chap_rows), sum(r[8] for r in chap_rows)])
S += ['## By chapter', ''] + table(['Chapter', 'Patterns', 'Target', 'Target E/M/H', 'Have', 'Gap', 'Gap E/M/H', 'Need a figure', 'Held (no target)'], chap_rows) + ['']
S += ['## By question slot', ''] + table(['Slot', 'Target', 'Target E/M/H', 'Gap', 'Gap E/M/H'],
     [[SLOT_NAME[s], sum(slot_t[s].values()), triple(slot_t[s]), sum(slot_g[s].values()), triple(slot_g[s])] for s in SLOTS]) + ['']

for d in chapters:
    S += [f"## {d['chapter']}", '']
    rows = []
    slots = collections.defaultdict(Counter)
    slotg = collections.defaultdict(Counter)
    for t in d['topics']:
        tt, th, tg = Counter(), Counter(), Counter()
        fig = 0
        last = None
        for p in t['patterns']:
            for k in DIFF:
                tt[k] += p['targets'].get(k, 0)
                th[k] += p['have'][k]
                tg[k] += p['gap'][k]
                slots[p['slot']][k] += p['targets'].get(k, 0)
                slotg[p['slot']][k] += p['gap'][k]
            fig += p['total'] if p['figure'] else 0
            la = last_asked(p)
            last = max(last or 0, la or 0) or None
        name = esc(t['name']) + (' *(verify)*' if t['scope'] == 'verify' else '')
        rows.append([name, len(t['patterns']), triple(tt), triple(th), triple(tg), fig, last or 'never'])
    S += table(['Topic', 'Patterns', 'Target E/M/H', 'Have E/M/H', 'Gap E/M/H', 'Need a figure', 'Last asked'], rows) + ['']
    S += table(['Slot', 'Target E/M/H', 'Gap E/M/H'], [[SLOT_NAME[s], triple(slots[s]), triple(slotg[s])] for s in SLOTS]) + ['']
open(os.path.join(ROOT, 'docs/content/question-bank-status.md'), 'w').write('\n'.join(S))

# ── exhaustive list ─────────────────────────────────────────────────────────
L = ['# Every question pattern: CBSE Class 10 Maths (Standard)', '',
     'Generated by `scripts/qb-report.py`; do not edit by hand. One row is one distinct kind of question in one slot.',
     '', '- **Target** and **Have** read easy / medium / hard.',
     '- **Fig**: needs a printed figure. **App**: application or higher-order.',
     '- **Asked in**: the board papers where this kind of question appeared, from the 149 Standard papers tagged (2011-2026, every set downloaded; main, compartment and second exams; each question linked to one pattern). Sources: PYQ_SOURCES.md. A blank means syllabus-only so far.',
     '- **Sample**: an illustration of the pattern, not a bank question. Samples have not gone through the full verification checks.',
     '- *(verify)* topics are waiting on the official syllabus.', '']
for d in chapters:
    L += [f"## {d['chapter']}", '']
    for t in d['topics']:
        L += [f"### {esc(t['name'])}" + (' *(verify)*' if t['scope'] == 'verify' else ''), '']
        if t.get('scopeNote'):
            L += [f"> {esc(t['scopeNote'])}", '']
        rows = []
        for p in sorted(t['patterns'], key=lambda p: SLOTS.index(p['slot'])):
            tg = Counter({k: p['targets'].get(k, 0) for k in DIFF})
            rows.append([p['id'], SLOT_NAME[p['slot']], esc(p['pattern']), triple(tg), triple(p['have']),
                         'Yes' if p['figure'] else '', 'Yes' if p['competency'] else '',
                         esc(', '.join(p.get('seenIn', []))), esc(p['sample'])])
        L += table(['Id', 'Slot', 'Pattern', 'Target', 'Have', 'Fig', 'App', 'Asked in', 'Sample'], rows) + ['']
open(os.path.join(ROOT, 'docs/content/question-patterns.md'), 'w').write('\n'.join(L))

print('patterns', sum(r[1] for r in chap_rows[:-1]), 'target', sum(total_t.values()), 'gap', sum(total_g.values()))
